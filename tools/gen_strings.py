"""Generate include/vanta/gen_strings.hpp from tools/strings.json.

Every string is encrypted with an independent 64-bit key at generation time;
the loader decrypts into a stack buffer on demand.  No plaintext literal for
these entries exists in the C++ sources or the linked image.

Run from the repository root:
    python -I tools/gen_strings.py
"""

from __future__ import annotations

import json
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "strings.json"
TARGET = ROOT / "include" / "vanta" / "gen_strings.hpp"

HEADER = """// AUTO-GENERATED by tools/gen_strings.py.  Do not edit.
#pragma once

#include "vanta/base.hpp"

namespace vanta {{
namespace str {{

enum Id : u32 {{
{enum}
}};

constexpr u32 kStringCount = static_cast<u32>(Id::kIdCount);
constexpr usize kMaxText = 256;

struct Blob {{
    const volatile u8* data;
    u32 len;
    u64 key;
}};

{blobs}

constexpr Blob kBlobs[kStringCount] = {{
{table}
}};

struct Text {{
    char data[kMaxText];
}};

inline Text text(Id id);
inline u32 length(Id id);

inline u32 length(Id id) {{
    u32 index = static_cast<u32>(id);
    return index < kStringCount ? kBlobs[index].len : 0;
}}

inline Text text(Id id) {{
    Text out{{}};
    u32 index = static_cast<u32>(id);
    if (index >= kStringCount) return out;
    const Blob& blob = kBlobs[index];
    const volatile u8* src = blob.data;
    u32 count = blob.len;
    if (count >= kMaxText) count = kMaxText - 1;
    u64 key = blob.key;
    for (u32 i = 0; i < count; ++i) {{
        u8 cipher = src[i];
        out.data[i] = static_cast<char>(
            cipher ^ static_cast<u8>(key >> ((i & 7) * 8)));
    }}
    out.data[count] = 0;
    return out;
}}

}}  // namespace str
}}  // namespace vanta
"""


def main() -> None:
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))
    enum_lines = []
    blob_defs = []
    table_rows = []
    for index, (name, value) in enumerate(entries.items()):
        raw = value.encode("utf-8")
        key = secrets.randbits(64)
        enc = bytes(b ^ ((key >> ((i & 7) * 8)) & 0xFF) for i, b in enumerate(raw))
        camel = "".join(part.capitalize() for part in name.lower().split("_"))
        enum_lines.append(f"    k{camel} = {index},")
        blob_defs.append(
            "constexpr u8 kData_%d[] = {%s};"
            % (index, ", ".join(f"0x{b:02x}" for b in enc) or "0")
        )
        table_rows.append(
            f"    {{kData_{index}, {len(raw)}u, 0x{key:016x}ull}},"
        )
    enum_lines.append("    kIdCount,")
    text = HEADER.format(
        enum="\n".join(enum_lines),
        blobs="\n".join(blob_defs),
        table="\n".join(table_rows),
    )
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
